import type { Page } from "@playwright/test";
import {
  appFetch,
  attachAndReload,
  openApp,
  openPanel,
  tabIdOf,
  trafficRow,
} from "./fixtures/panel.ts";
import { expect, test } from "./fixtures/extension.ts";

// 007 T069 (plan.md "Rendimiento"): cada formato de un body de 1 MB se genera en < 300 ms y un lote
// de 50 requests en < 3 s, medido desde el clic hasta ver el código en el visor.

const dialog = (panel: Page) => panel.getByRole("dialog", { name: /^Export/ });
const firstLine = (panel: Page) => dialog(panel).locator(".cm-line").first();

test(
  "exportar un body de 1 MB (< 300 ms por formato) y un lote de 50 (< 3 s)",
  { tag: "@perf" },
  async ({ context, nahualWorker, extensionId, servers }) => {
    test.setTimeout(120_000);
    const app = await openApp(context, servers.appOrigin);
    const tabId = await tabIdOf(nahualWorker, `${servers.appOrigin}/`);
    const panel = await openPanel(context, extensionId, tabId);
    await panel.setViewportSize({ width: 1280, height: 800 });
    await attachAndReload(panel, app);

    const large = await appFetch(app, `${servers.apiOrigin}/export/large`);
    expect(large.body.length).toBeGreaterThan(1_000_000);
    // Por debajo de `exportInlineBodyBytes` (1 MiB): el body entra entero en el código.
    expect(large.body.length).toBeLessThan(1_048_576);
    await trafficRow(panel, "/export/large").first().click({ button: "right" });
    await panel.getByRole("menuitem", { name: "Export as…" }).click();
    await expect(firstLine(panel)).toBeVisible();

    const times: Record<string, number> = {};
    // Se pasa por otro formato antes de cada medición: cada clic genera de nuevo.
    for (const name of ["cURL", "fetch", "Vitest test", "MSW handler", "Zod schema", "Postman"]) {
      const other = name === "cURL" ? "fetch" : "cURL";
      await dialog(panel).getByRole("tab", { name: other, exact: true }).click();
      await expect(firstLine(panel)).toHaveText(/Generated by Nahual/);
      const start = Date.now();
      await dialog(panel).getByRole("tab", { name, exact: true }).click();
      await expect(dialog(panel).getByRole("tab", { name, exact: true })).toHaveAttribute(
        "aria-selected",
        "true",
      );
      await expect(firstLine(panel)).toHaveText(/Generated by Nahual|^\{/, { timeout: 5_000 });
      times[name] = Date.now() - start;
    }
    console.log("1 MB por formato (ms)", times);
    for (const [name, ms] of Object.entries(times)) expect(ms, name).toBeLessThan(300);
    await panel.keyboard.press("Escape");

    // Lote de 50.
    for (let page = 1; page <= 50; page++)
      await appFetch(app, `${servers.apiOrigin}/export/items?page=${page}`);
    for (let page = 1; page <= 50; page++)
      await trafficRow(panel, `/export/items?page=${page}`)
        .filter({ has: panel.getByRole("gridcell", { name: "GET", exact: true }) })
        .first()
        .getByRole("checkbox")
        .check();
    const bar = panel.getByRole("toolbar", { name: /selected requests/i });
    await expect(bar).toContainText("50");
    const start = Date.now();
    await bar.getByRole("button", { name: "Export MSW handlers" }).click();
    await expect(firstLine(panel)).toHaveText(/^\/\/ Generated by Nahual/, { timeout: 10_000 });
    const batch = Date.now() - start;
    console.log("lote de 50 (ms)", batch);
    expect(batch).toBeLessThan(3_000);
  },
);
