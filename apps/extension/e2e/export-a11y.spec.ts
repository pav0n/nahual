import type { Page } from "@playwright/test";
import { expectNoHorizontalScroll, expectNoSeriousViolations } from "./fixtures/axe.ts";
import {
  attachAndReload,
  callApi,
  openApp,
  openPanel,
  tabIdOf,
  trafficRow,
} from "./fixtures/panel.ts";
import { expect, test } from "./fixtures/extension.ts";

// 007 (SC-012, T067): axe y sin scroll horizontal en "Exportar como…" (cada formato y con la
// confirmación abierta) en claro y oscuro, a 320, 800 y 1280 px; recorrido solo con teclado.

const FORMATS = ["cURL", "fetch", "Vitest test", "MSW handler", "Zod schema", "Postman"];
const dialog = (panel: Page) => panel.getByRole("dialog", { name: /^Export/ });
const requestRow = (panel: Page) =>
  trafficRow(panel, "/export/items")
    .filter({ has: panel.getByRole("gridcell", { name: "GET", exact: true }) })
    .first();

for (const colorScheme of ["light", "dark"] as const) {
  for (const width of [320, 800, 1280]) {
    test(`exportar: cada formato y la confirmación, tema ${colorScheme}, ${width} px`, async ({
      context,
      nahualWorker,
      extensionId,
      servers,
    }) => {
      const app = await openApp(context, servers.appOrigin);
      const tabId = await tabIdOf(nahualWorker, `${servers.appOrigin}/`);
      const panel = await openPanel(context, extensionId, tabId);
      await panel.emulateMedia({ colorScheme });
      await panel.setViewportSize({ width, height: 800 });
      await attachAndReload(panel, app);
      await callApi(app, "export-items");

      await requestRow(panel).click({ button: "right" });
      await panel.getByRole("menuitem", { name: "Export as…" }).click();
      await expect(dialog(panel).locator(".cm-content")).toBeVisible();
      for (const name of FORMATS) {
        await dialog(panel).getByRole("tab", { name, exact: true }).click();
        await expect(dialog(panel).getByRole("tab", { name, exact: true })).toHaveAttribute(
          "aria-selected",
          "true",
        );
        await expectNoSeriousViolations(panel, `exportar ${name}`);
        await expectNoHorizontalScroll(panel);
      }
      await dialog(panel).getByRole("switch", { name: "Include sensitive values" }).click();
      await expect(panel.getByRole("dialog", { name: "Include sensitive values?" })).toBeVisible();
      await expectNoSeriousViolations(panel, "confirmación de incluir valores sensibles");
      await expectNoHorizontalScroll(panel);
    });
  }
}

test("exportar solo con teclado: atajo, flechas entre formatos, copiar con Enter, Tab sale del visor y Esc cierra", async ({
  context,
  nahualWorker,
  extensionId,
  servers,
}) => {
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  const app = await openApp(context, servers.appOrigin);
  const tabId = await tabIdOf(nahualWorker, `${servers.appOrigin}/`);
  const panel = await openPanel(context, extensionId, tabId);
  await panel.setViewportSize({ width: 1100, height: 800 });
  await attachAndReload(panel, app);
  await callApi(app, "export-items");
  await requestRow(panel).click();
  await panel.locator("body").focus();
  await panel.keyboard.press("Alt+Shift+E");
  await expect(dialog(panel)).toBeVisible();

  const tab = (name: string) => dialog(panel).getByRole("tab", { name, exact: true });
  const selected = dialog(panel).locator('[role="tab"][aria-selected="true"]');
  await selected.focus();
  const first = await selected.textContent();
  await panel.keyboard.press("ArrowRight");
  await expect(selected).not.toHaveText(first ?? "");
  await expect(selected).toBeFocused();
  await tab("cURL").focus();
  await panel.keyboard.press("Enter");
  await expect(tab("cURL")).toHaveAttribute("aria-selected", "true");

  // El visor es de solo lectura: no atrapa Tab (el editor de hooks sí, y se sale con Esc + Tab);
  // Esc cierra el diálogo, como en el resto del panel.
  await dialog(panel).locator(".cm-content").focus();
  await panel.keyboard.press("Tab");
  await expect(dialog(panel).locator(".cm-content")).not.toBeFocused();
  await expect(dialog(panel)).toBeVisible();

  const copy = dialog(panel).getByRole("button", { name: "Copy" });
  await copy.focus();
  await panel.keyboard.press("Enter");
  expect(await panel.evaluate(() => navigator.clipboard.readText())).toMatch(
    /^# Generated by Nahual/,
  );
  await panel.keyboard.press("Escape");
  await expect(dialog(panel)).toBeHidden();
});
