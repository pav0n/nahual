import { REDACTED } from "../sensitive.ts";
import {
  endpointOf,
  isJsonType,
  mediaType,
  omittedNote,
  parseJson,
  pathname,
  type ExportMerge,
  type ExportOmission,
  type ExportOptions,
} from "./common.ts";
import { jsString, jsValue } from "./js.ts";
import type { ExportSource } from "./source.ts";

const WIDTH = 100;
const METHODS = new Set(["get", "post", "put", "patch", "delete", "head", "options"]);
/** Los pone el runtime al responder; copiarlos rompería la respuesta (research R5). */
const DROP = new Set(["content-length", "content-encoding", "transfer-encoding"]);

/** URL sin query ni fragmento: MSW no usa la query para emparejar y avisa si está. */
function withoutQuery(url: string): string {
  try {
    const parsed = new URL(url);
    return `${parsed.origin}${parsed.pathname}`;
  } catch {
    return url.split(/[?#]/, 1)[0] ?? url;
  }
}

const queryOf = (url: string) => /\?[^#]*/.exec(url)?.[0] ?? "";

/** `callee(arg, …)` en una línea si cabe a partir de `indent`; si no, un argumento por línea. */
function call(callee: string, args: unknown[], indent: number, raw: string[] = []) {
  const rendered = [...raw, ...args.map((a) => jsValue(a, 0, -Infinity))];
  const flat = `${callee}(${rendered.join(", ")})`;
  if (indent + flat.length + 1 <= WIDTH) return flat;
  const pad = " ".repeat(indent + 2);
  const lines = [
    ...raw.map((r) => `${pad}${r},`),
    ...args.map((a) => `${pad}${jsValue(a, indent + 2)},`),
  ];
  return `${callee}(\n${lines.join("\n")}\n${" ".repeat(indent)})`;
}

function responseExpr(source: ExportSource, notes: string[]): string {
  const response = source.response;
  if (!response) return "new HttpResponse(null, { status: 502 })";
  const body = response.body;
  const json = body.kind === "text" ? parseJson(body.text) : { ok: false as const };
  const asJson =
    body.kind === "text" &&
    json.ok &&
    (isJsonType(body.contentType) || mediaType(body.contentType) === "");
  const headers = Object.fromEntries(
    response.headers
      .filter((h) => {
        const name = h.name.toLowerCase();
        if (DROP.has(name) || h.value === REDACTED) return false;
        // `HttpResponse.json` pone su propio content-type.
        return !(asJson && name === "content-type");
      })
      .map((h) => [h.name.toLowerCase(), h.value]),
  );
  const init = Object.keys(headers).length
    ? { status: response.status, headers }
    : { status: response.status };
  if (asJson && json.ok) return call("HttpResponse.json", [json.value, init], 4);
  if (body.kind === "text") return call("HttpResponse.text", [init], 4, [jsString(body.text)]);
  if (body.kind === "omitted") notes.push(omittedNote(body));
  return call("new HttpResponse", [init], 4, ["null"]);
}

/**
 * Archivo de handlers MSW (007, research R5, FR-014, FR-016): un handler por endpoint (método y
 * ruta sin query) en el orden de la lista; si varios requests comparten endpoint, responde la
 * última respuesta y se avisa. Los requests sin respuesta se omiten.
 */
export function msw(
  sources: readonly ExportSource[],
  options: ExportOptions,
): { code: string; omitted: ExportOmission[]; merged: ExportMerge[] } {
  const omitted: ExportOmission[] = [];
  const groups = new Map<string, ExportSource[]>();
  sources.forEach((source, index) => {
    if (!source.response) {
      omitted.push({ index, reasonKey: "export_reason_no_response" });
      return;
    }
    const endpoint = endpointOf(source);
    groups.set(endpoint, [...(groups.get(endpoint) ?? []), source]);
  });
  const merged: ExportMerge[] = [];
  const handlers: string[] = [];
  for (const [endpoint, group] of groups) {
    const source = group[group.length - 1] as ExportSource;
    const method = source.request.method.toLowerCase();
    const notes: string[] = [];
    const expr = responseExpr(source, notes);
    let comment = `${source.request.method} ${pathname(source.request.url)}${queryOf(source.request.url)} · captured ${source.response?.status ?? ""}`;
    if (group.length > 1) {
      merged.push({ endpoint, count: group.length });
      comment += ` · merged ${group.length} requests`;
    }
    const fn = METHODS.has(method) ? `http.${method}` : "http.all";
    handlers.push(
      [
        `  // ${comment}`,
        ...notes.map((n) => `  // ${n}`),
        `  ${fn}(${jsString(withoutQuery(source.request.url))}, () =>`,
        `    ${expr},`,
        "  ),",
      ].join("\n"),
    );
  }
  const code = [
    `// Generated by Nahual ${options.appVersion} · msw 3 (also runs on msw 2)`,
    'import { http, HttpResponse } from "msw";',
    "",
    "export const handlers = [",
    ...handlers,
    "];",
    "",
    '// Node: import { setupServer } from "msw/node"; setupServer(...handlers).listen();',
    "",
  ].join("\n");
  return { code, omitted, merged };
}
