import {
  commentText,
  isJsonType,
  mediaType,
  omittedNote,
  parseJson,
  type ExportOptions,
} from "./common.ts";
import { jsString, jsValue } from "./js.ts";
import type { ExportHeader, ExportSource } from "./source.ts";

/** Headers como objeto; con nombres repetidos, como lista de pares (los dos son `HeadersInit`). */
export function headersLiteral(headers: readonly ExportHeader[], indent: number, column: number) {
  const names = headers.map((h) => h.name);
  if (new Set(names).size !== names.length)
    return jsValue(
      headers.map((h) => [h.name, h.value]),
      indent,
      column,
    );
  return jsValue(Object.fromEntries(headers.map((h) => [h.name, h.value])), indent, column);
}

/**
 * `fetch(url, { … })` sin `await` ni lectura, con la sangría `indent` (0 en fetch, 4 en Vitest).
 * `before` recibe las líneas que van antes (el `FormData`, comentarios de lo omitido).
 */
export function fetchCall(source: ExportSource, indent: number, before: string[]): string[] {
  const { request } = source;
  const pad = " ".repeat(indent);
  let body: string | null = null;
  const b = request.body;
  const at = (prefix: string) => indent + prefix.length;
  if (b.kind === "text") {
    const json = parseJson(b.text);
    body =
      json.ok && (isJsonType(b.contentType) || mediaType(b.contentType) === "")
        ? `JSON.stringify(${jsValue(json.value, indent + 2, at("  body: JSON.stringify("))})`
        : jsString(b.text);
  } else if (b.kind === "form") {
    body = `new URLSearchParams(${jsValue(
      b.fields.map((f) => [f.name, f.value]),
      indent + 2,
      at("  body: new URLSearchParams("),
    )})`;
  } else if (b.kind === "multipart") {
    before.push(`${pad}const form = new FormData();`);
    for (const part of b.parts)
      before.push(
        part.kind === "field"
          ? `${pad}form.append(${jsString(part.name)}, ${jsString(part.value)});`
          : `${pad}// ${commentText(`omitted file part: ${part.name} (${part.filename})`)}`,
      );
    body = "form";
  } else if (b.kind === "omitted") {
    before.push(`${pad}// ${omittedNote(b)}`);
  }
  const headers = request.headers.filter(
    (h) => !(b.kind === "multipart" && h.name === "content-type"),
  );
  const init = [`${pad}  method: ${jsString(request.method)},`];
  if (headers.length > 0)
    init.push(`${pad}  headers: ${headersLiteral(headers, indent + 2, at("  headers: "))},`);
  if (body !== null) init.push(`${pad}  body: ${body},`);
  return [`fetch(${jsString(request.url)}, {`, ...init, `${pad}})`];
}

/**
 * Llamada `fetch()` (007, contracts/exporters.md, research R4): mismo método, URL, headers y body;
 * un body JSON va como `JSON.stringify(objeto)`, un formulario como `URLSearchParams` y un
 * multipart como `FormData` (sin `content-type`, que pone el navegador con su boundary).
 */
export function fetchCode(source: ExportSource, options: ExportOptions): string {
  const { response } = source;
  const before: string[] = [`// Generated by Nahual ${options.appVersion}`];
  const [first, ...rest] = fetchCall(source, 0, before);
  const reader =
    response?.body.kind === "text" && parseJson(response.body.text).ok ? "json" : "text";
  const captured = response
    ? ` // ${commentText(`captured: ${response.status}${response.mimeType ? ` ${response.mimeType}` : ""}`)}`
    : " // no response captured";
  return [
    ...before,
    `const response = await ${first}`,
    ...rest.slice(0, -1),
    `${rest[rest.length - 1]};`,
    `const data = await response.${reader}();${captured}`,
    "",
  ].join("\n");
}
