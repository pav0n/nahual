import { commentText, omittedNote, type ExportOptions } from "./common.ts";
import type { ExportSource } from "./source.ts";

/** Comillas simples de shell: `'` se escribe `'\''`. */
const quote = (text: string) => `'${text.replaceAll("'", "'\\''")}'`;

/**
 * Comando cURL (007, contracts/exporters.md, research R4): una opción por línea, comillas simples,
 * `-X` salvo en un `GET` sin body. Formularios con `--data-urlencode` y multipart con
 * `--form-string` (literal: un valor que empieza por `@` no sube un archivo). Los comentarios de
 * lo omitido van antes del comando para no romper las continuaciones.
 */
export function curl(source: ExportSource, options: ExportOptions): string {
  const { request } = source;
  const notes = [`# Generated by Nahual ${options.appVersion}`];
  const body: string[] = [];
  let hasBody = true;
  switch (request.body.kind) {
    case "text":
      body.push(`--data-raw ${quote(request.body.text)}`);
      break;
    case "form":
      for (const f of request.body.fields)
        body.push(`--data-urlencode ${quote(`${f.name}=${f.value}`)}`);
      break;
    case "multipart":
      for (const part of request.body.parts) {
        if (part.kind === "field")
          body.push(`--form-string ${quote(`${part.name}=${part.value}`)}`);
        else notes.push(commentText(`# omitted file part: ${part.name} (${part.filename})`));
      }
      break;
    case "omitted":
      notes.push(`# ${omittedNote(request.body)}`);
      hasBody = false;
      break;
    case "none":
      hasBody = false;
  }
  const headers = request.headers.filter(
    // cURL pone el content-type multipart con su propio boundary.
    (h) => !(request.body.kind === "multipart" && h.name === "content-type"),
  );
  const options_ = [
    ...(request.method !== "GET" || hasBody ? [`-X ${request.method}`] : []),
    ...headers.map((h) => `-H ${quote(`${h.name}: ${h.value}`)}`),
    ...body,
  ];
  const command = [`curl ${quote(request.url)}`, ...options_.map((o) => `  ${o}`)].join(" \\\n");
  return `${notes.join("\n")}\n${command}\n`;
}
