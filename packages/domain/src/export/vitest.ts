import type { RedactedSite } from "../sensitive.ts";
import { endpointOf, mediaType, parseJson, type ExportOptions } from "./common.ts";
import { fetchCall } from "./fetch.ts";
import { jsString } from "./js.ts";
import type { ExportSource } from "./source.ts";
import { inferResponses, zodExpression } from "./zod.ts";

function originOf(url: string): string {
  try {
    return new URL(url).origin;
  } catch {
    return url;
  }
}

/**
 * Test Vitest de contrato (007, research R7, FR-013): envía el request real y comprueba el status
 * y que el body cumple el schema inferido. Los valores redactados llegan como marcadores de
 * entorno (`envMarker`) y se leen de `process.env` con un error claro si faltan; si el servidor
 * no responde, el test falla diciéndolo. Quien llama garantiza que hay respuesta.
 */
export function vitestCode(
  source: ExportSource,
  redacted: readonly RedactedSite[],
  options: ExportOptions,
): string {
  const response = source.response;
  if (!response) throw new Error("vitest export needs a captured response");
  const body = response.body;
  const json = body.kind === "text" && parseJson(body.text).ok;
  const vars = [...new Set(redacted.filter((s) => s.side === "request").map((s) => s.envVar))];
  const lines = [
    `// Generated by Nahual ${options.appVersion} · vitest 5${json ? " · zod 4" : ""}`,
  ];
  if (vars.length) lines.push(`// Environment variables required: ${vars.join(", ")}`);
  lines.push('import { describe, expect, it } from "vitest";');
  if (json) lines.push('import { z } from "zod";');
  lines.push("");
  if (vars.length)
    lines.push(
      "const env = (name: string) => {",
      "  const value = process.env[name];",
      "  if (!value) throw new Error(`Missing ${name}`);",
      "  return value;",
      "};",
      "",
    );
  if (json) {
    const head = "const schema = ";
    lines.push(`${head}${zodExpression(inferResponses([source]), 0, head.length)};`, "");
  }
  const origin = originOf(source.request.url);
  const before: string[] = [];
  const [first, ...rest] = fetchCall(source, 4, before);
  const checks = json
    ? [
        "    const body: unknown = await response.json();",
        "    expect(schema.safeParse(body).error).toBeUndefined();",
      ]
    : [
        `    expect(response.headers.get("content-type")).toContain(${jsString(
          mediaType(response.headers.find((h) => h.name.toLowerCase() === "content-type")?.value) ||
            mediaType(response.mimeType),
        )});`,
      ];
  lines.push(
    `describe(${jsString(endpointOf(source))}, () => {`,
    `  it(${jsString(`responds ${response.status} with the captured shape`)}, async () => {`,
    ...before,
    `    const response = await ${first}`,
    ...rest.slice(0, -1),
    `${rest[rest.length - 1]}.catch((error: unknown) => {`,
    `      throw new Error(\`Server unreachable at ${origin.replaceAll("`", "\\`").replaceAll("${", "\\${")}: \${String(error)}\`);`,
    "    });",
    `    expect(response.status).toBe(${response.status});`,
    ...checks,
    "  });",
    "});",
    "",
  );
  return lines.join("\n");
}
