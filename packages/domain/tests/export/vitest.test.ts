import { describe, expect, it } from "vitest";
import { envMarker } from "../../src/export/js.ts";
import { vitestCode } from "../../src/export/vitest.ts";
import { redactExportSource } from "../../src/sensitive.ts";
import { getBinary, getItems, postItem } from "../fixtures-export.ts";
import { OPTIONS, leaked, sourceOf } from "./helpers.ts";

/** Como lo prepara `exportAs` para Vitest: cada valor sensible, una variable de entorno. */
const render = (f: Parameters<typeof sourceOf>[0]) => {
  const { source, redacted } = redactExportSource(sourceOf(f), (site) => envMarker(site.envVar));
  return vitestCode(source, redacted, OPTIONS);
};

describe("test Vitest de contrato (007, research R7, FR-013)", () => {
  it("GET: variables de entorno, fetch con mensaje si no responde, status y schema", () => {
    expect(render(getItems)).toBe(
      [
        "// Generated by Nahual 1.0.0 · vitest 5 · zod 4",
        "// Environment variables required: NAHUAL_AUTHORIZATION",
        'import { describe, expect, it } from "vitest";',
        'import { z } from "zod";',
        "",
        "const env = (name: string) => {",
        "  const value = process.env[name];",
        "  if (!value) throw new Error(`Missing ${name}`);",
        "  return value;",
        "};",
        "",
        "const schema = z.object({",
        "  items: z.array(",
        "    z.object({ id: z.number().int(), name: z.string(), deletedAt: z.iso.datetime().nullable() }),",
        "  ),",
        "  next: z.string(),",
        "});",
        "",
        'describe("GET /export/items", () => {',
        '  it("responds 200 with the captured shape", async () => {',
        '    const response = await fetch("http://127.0.0.1:4311/export/items?page=1", {',
        '      method: "GET",',
        "      headers: {",
        '        accept: "application/json",',
        '        authorization: env("NAHUAL_AUTHORIZATION"),',
        '        "user-agent": "Mozilla/5.0",',
        "      },",
        "    }).catch((error: unknown) => {",
        "      throw new Error(`Server unreachable at http://127.0.0.1:4311: ${String(error)}`);",
        "    });",
        "    expect(response.status).toBe(200);",
        "    const body: unknown = await response.json();",
        "    expect(schema.safeParse(body).error).toBeUndefined();",
        "  });",
        "});",
        "",
      ].join("\n"),
    );
  });

  it("query y body sensibles salen de variables de entorno, sin fugas", () => {
    const code = render(postItem);
    expect(code).toContain(
      "// Environment variables required: NAHUAL_COOKIE, NAHUAL_X_API_KEY, NAHUAL_QUERY_TOKEN, NAHUAL_BODY_PASSWORD",
    );
    expect(code).toContain(
      'fetch(`http://127.0.0.1:4311/export/items?token=${env("NAHUAL_QUERY_TOKEN")}&lang=es`',
    );
    expect(code).toContain('password: env("NAHUAL_BODY_PASSWORD")');
    expect(leaked(code)).toEqual([]);
  });

  it("sin valores sensibles no hay env; respuesta no JSON ⇒ solo status y content-type", () => {
    const code = render(getBinary);
    expect(code).not.toContain("const env");
    expect(code).not.toContain("Environment variables");
    expect(code).not.toContain('from "zod"');
    expect(code).toContain('expect(response.headers.get("content-type")).toContain("image/png");');
  });
});
