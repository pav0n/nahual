import { describe, expect, it } from "vitest";
import { msw } from "../../src/export/msw.ts";
import { failed, getBinary, getItems, itemPages, postItem } from "../fixtures-export.ts";
import { OPTIONS, leaked, nth, redacted, sourceOf } from "./helpers.ts";

const render = (fixtures: Parameters<typeof redacted>[0][]) =>
  msw(
    fixtures.map((f) => redacted(f).source),
    OPTIONS,
  );

describe("handlers MSW (007, research R5, FR-014, FR-016)", () => {
  it("un handler por endpoint, ruta sin query, query en comentario, headers filtrados", () => {
    const { code } = render([getItems]);
    expect(code).toBe(
      [
        "// Generated by Nahual 1.0.0 · msw 3 (also runs on msw 2)",
        'import { http, HttpResponse } from "msw";',
        "",
        "export const handlers = [",
        "  // GET /export/items?page=1 · captured 200",
        '  http.get("http://127.0.0.1:4311/export/items", () =>',
        "    HttpResponse.json(",
        "      {",
        "        items: [",
        '          { id: 1, name: "item-1", deletedAt: "2026-10-25T20:00:00.000Z" },',
        '          { id: 2, name: "item-2", deletedAt: null },',
        "        ],",
        '        next: "/export/items?page=2",',
        "      },",
        '      { status: 200, headers: { "x-request-id": "req-13-7" } },',
        "    ),",
        "  ),",
        "];",
        "",
        '// Node: import { setupServer } from "msw/node"; setupServer(...handlers).listen();',
        "",
      ].join("\n"),
    );
  });

  it("varios del mismo endpoint ⇒ uno con la última respuesta y aviso de fusionados", () => {
    const { code, merged } = render([nth(itemPages, 0), postItem, nth(itemPages, 1)]);
    expect(merged).toEqual([{ endpoint: "GET /export/items", count: 2 }]);
    expect(code.match(/http\.get\(/g)).toHaveLength(1);
    expect(code).toContain("// GET /export/items?page=2 · captured 200 · merged 2 requests");
    expect(code).toContain('"item-3"');
    expect(code.indexOf("http.get(")).toBeLessThan(code.indexOf("http.post("));
  });

  it("sin respuesta ⇒ omitido; binario ⇒ sin body con comentario; texto ⇒ HttpResponse.text", () => {
    const { code, omitted } = render([failed, getBinary]);
    expect(omitted).toEqual([{ index: 0, reasonKey: "export_reason_no_response" }]);
    expect(code).toContain("// body omitted: binary (8 B)");
    expect(code).toContain(
      'new HttpResponse(null, { status: 200, headers: { "content-type": "image/png" } })',
    );
    const text = sourceOf(getItems);
    text.response = {
      ...nth(
        [text.response].filter((r) => r !== null),
        0,
      ),
      headers: [{ name: "content-type", value: "text/plain" }],
      body: { kind: "text", text: "hola", contentType: "text/plain" },
    };
    expect(msw([text], OPTIONS).code).toContain(
      'HttpResponse.text("hola", { status: 200, headers: { "content-type": "text/plain" } })',
    );
  });

  it("nunca filtra valores sensibles ni set-cookie redactado", () => {
    const { code } = render([getItems, postItem]);
    expect(leaked(code)).toEqual([]);
    expect(code).not.toContain("set-cookie");
  });
});
