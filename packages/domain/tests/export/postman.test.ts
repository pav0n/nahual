import { describe, expect, it } from "vitest";
import { PostmanCollectionSchema, postman } from "../../src/export/postman.ts";
import { redactExportSource } from "../../src/sensitive.ts";
import { failed, getItems, itemPages, postForm, postItem, postUpload } from "../fixtures-export.ts";
import { OPTIONS, leaked, sourceOf } from "./helpers.ts";

const prepare = (fixtures: Parameters<typeof sourceOf>[0][]) =>
  fixtures.map((f) => redactExportSource(sourceOf(f), (site) => `{{${site.postmanVar}}}`));
const render = (fixtures: Parameters<typeof sourceOf>[0][], site?: string) =>
  postman(prepare(fixtures), { ...OPTIONS, ...(site ? { site } : {}) });

describe("colección de Postman v2.1.0 (007, research R8, FR-016b)", () => {
  it("valida contra el subconjunto del schema y no lleva _postman_id", () => {
    const collection = JSON.parse(render([getItems, postItem, postForm, postUpload, failed]));
    expect(PostmanCollectionSchema.safeParse(collection).success).toBe(true);
    expect(JSON.stringify(collection)).not.toContain("_postman_id");
    expect(collection.info).toEqual({
      name: "Nahual · http://127.0.0.1:4311",
      description: "Generated by Nahual 1.0.0 · captured 2025-10-25T20:00:00.000Z",
      schema: "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
    });
  });

  it("un elemento por request en orden, con la respuesta como ejemplo", () => {
    const collection = JSON.parse(render([getItems, postItem], "http://127.0.0.1:4310"));
    expect(collection.item.map((i: { name: string }) => i.name)).toEqual([
      "GET /export/items",
      "POST /export/items",
    ]);
    const [get] = collection.item;
    expect(get.request.url).toEqual({
      raw: "http://127.0.0.1:4311/export/items?page=1",
      protocol: "http",
      host: ["127", "0", "0", "1"],
      port: "4311",
      path: ["export", "items"],
      query: [{ key: "page", value: "1" }],
    });
    expect(get.response[0]).toMatchObject({
      name: "Captured",
      code: 200,
      status: "OK",
      _postman_previewlanguage: "json",
    });
  });

  it("valores sensibles como variables de colección vacías, sin fugas", () => {
    const code = render([getItems, postItem]);
    const collection = JSON.parse(code);
    expect(leaked(code)).toEqual([]);
    expect(collection.variable).toEqual([
      { key: "nahual_authorization", value: "" },
      { key: "nahual_set_cookie", value: "" },
      { key: "nahual_cookie", value: "" },
      { key: "nahual_x_api_key", value: "" },
      { key: "nahual_query_token", value: "" },
      { key: "nahual_body_password", value: "" },
    ]);
    expect(collection.item[0].request.header).toContainEqual({
      key: "authorization",
      value: "{{nahual_authorization}}",
    });
  });

  it("formulario urlencoded, multipart formdata sin archivos y body JSON raw", () => {
    const [form, upload, post] = JSON.parse(render([postForm, postUpload, postItem])).item;
    expect(form.request.body).toEqual({
      mode: "urlencoded",
      urlencoded: [
        { key: "a", value: "1" },
        { key: "session_id", value: "{{nahual_body_session_id}}" },
      ],
    });
    expect(upload.request.body).toEqual({
      mode: "formdata",
      formdata: [{ key: "note", value: "hola", type: "text" }],
    });
    expect(upload.description).toBe("omitted file part: file (photo.png)");
    expect(post.request.body.mode).toBe("raw");
    expect(post.request.body.options).toEqual({ raw: { language: "json" } });
  });

  it("es determinista y acepta lotes", () => {
    expect(render(itemPages)).toBe(render(itemPages));
    expect(JSON.parse(render(itemPages)).item).toHaveLength(3);
  });
});
