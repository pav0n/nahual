import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { describe, expect, it } from "vitest";
import type { ZodType } from "zod";
import { inferType, mergeTypes, schemaName, zodSchema } from "../../src/export/zod.ts";
import { getItems, itemPages, postItem } from "../fixtures-export.ts";
import { OPTIONS, nth, sourceOf } from "./helpers.ts";

/** Evalúa el código generado con Zod real: se escribe junto a `node_modules` y se importa. */
async function load(code: string, name: string): Promise<ZodType> {
  const dir = path.resolve(import.meta.dirname, "../../node_modules/.cache/nahual-zod");
  mkdirSync(dir, { recursive: true });
  const file = path.join(dir, `${name}-${Math.random().toString(36).slice(2)}.ts`);
  writeFileSync(file, code);
  const module = (await import(pathToFileURL(file).href)) as Record<string, ZodType>;
  const schema = Object.values(module)[0];
  if (!schema) throw new Error("sin schema");
  return schema;
}

const pages = itemPages.map(sourceOf);
const bodies = pages.map((s) =>
  s.response?.body.kind === "text" ? JSON.parse(s.response.body.text) : null,
);

describe("inferencia del schema Zod (007, research R6, FR-015)", () => {
  it("mergeTypes es conmutativa y asociativa", () => {
    const types = bodies.map((v) => inferType(v));
    const [a, b, c] = [nth(types, 0), nth(types, 1), nth(types, 2)];
    expect(mergeTypes(a, b)).toEqual(mergeTypes(b, a));
    expect(mergeTypes(mergeTypes(a, b), c)).toEqual(mergeTypes(a, mergeTypes(b, c)));
  });

  it("varias respuestas: ausentes ⇒ optional, null ⇒ nullable, enteros ⇒ int, ISO ⇒ datetime", () => {
    const code = zodSchema(pages, OPTIONS);
    expect(code).toBe(
      [
        "// Generated by Nahual 1.0.0 · zod 4 · inferred from 3 responses of GET /export/items",
        'import { z } from "zod";',
        "",
        "export const exportItemsResponse = z.object({",
        "  items: z.array(",
        "    z.object({ id: z.number().int(), name: z.string(), deletedAt: z.iso.datetime().nullable() }),",
        "  ),",
        "  next: z.string().optional(),",
        "});",
        "export type ExportItemsResponse = z.infer<typeof exportItemsResponse>;",
        "",
      ].join("\n"),
    );
  });

  it("el schema generado acepta todas las muestras y rechaza un tipo cambiado (SC-003)", async () => {
    const schema = await load(zodSchema(pages, OPTIONS), "pages");
    for (const body of bodies) expect(schema.safeParse(body).success).toBe(true);
    const changed = structuredClone(bodies[0]) as { items: { id: unknown }[] };
    nth(changed.items, 0).id = "1";
    expect(schema.safeParse(changed).success).toBe(false);
  });

  it("arrays heterogéneos ⇒ union ordenada; vacíos ⇒ unknown; profundidad > 10 ⇒ unknown", async () => {
    let deep: unknown = 1;
    for (let i = 0; i < 12; i++) deep = { d: deep };
    const code = zodSchema(
      [
        {
          request: { method: "GET", url: "http://a.test/", headers: [], body: { kind: "none" } },
          response: {
            status: 200,
            headers: [],
            mimeType: "application/json",
            body: {
              kind: "text",
              contentType: "application/json",
              text: JSON.stringify({ mixed: [1, "a", true], empty: [], deep }),
            },
          },
          capturedAt: 0,
        },
      ],
      OPTIONS,
    );
    expect(code).toContain("mixed: z.array(z.union([z.boolean(), z.number().int(), z.string()]))");
    expect(code).toContain("empty: z.array(z.unknown())");
    expect(code).toContain("z.unknown() /* deeper than 10 levels */");
    expect(code).toContain("export const rootResponse =");
    const schema = await load(code, "mixed");
    expect(schema.safeParse({ mixed: [2, "b"], empty: [], deep }).success).toBe(true);
  });

  it("schemaName sale de la ruta sin segmentos numéricos y siempre es un identificador", () => {
    expect(schemaName("/export/items/4")).toBe("exportItems");
    expect(schemaName("/")).toBe("root");
    expect(schemaName("/2024/v1-users")).toBe("v1Users");
    expect(schemaName("/123")).toBe("root");
  });

  it("una sola respuesta: tipos exactos; el comentario dice 1 response", () => {
    const code = zodSchema([sourceOf(getItems)], OPTIONS);
    expect(code).toContain("inferred from 1 response of GET /export/items");
    expect(code).toContain("deletedAt: z.iso.datetime().nullable()");
    expect(code).toContain("next: z.string(),");
    expect(zodSchema([sourceOf(postItem)], OPTIONS)).toContain("created: z.boolean()");
  });
});
