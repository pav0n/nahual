import { describe, expect, it } from "vitest";
import { envMarker, jsString, jsValue } from "../../src/export/js.ts";
import { fetchCode } from "../../src/export/fetch.ts";
import { getItems, postBig, postForm, postItem, postUpload } from "../fixtures-export.ts";
import { OPTIONS, leaked, redacted } from "./helpers.ts";

const render = (f: Parameters<typeof redacted>[0]) => fetchCode(redacted(f).source, OPTIONS);

describe("literales JS (007)", () => {
  it("jsValue: claves identificador sin comillas, el resto con comillas; en línea si cabe", () => {
    expect(jsValue({ a: 1, "content-type": "x", list: [true, null] })).toBe(
      '{ a: 1, "content-type": "x", list: [true, null] }',
    );
    expect(jsValue({})).toBe("{}");
    expect(jsValue([])).toBe("[]");
  });

  it("jsValue parte en varias líneas lo largo, con sangría", () => {
    const value = { items: [{ id: 1, name: "x".repeat(65) }], next: "/n" };
    expect(jsValue(value)).toBe(
      ["{", '  items: [{ id: 1, name: "' + "x".repeat(65) + '" }],', '  next: "/n",', "}"].join(
        "\n",
      ),
    );
  });

  it("jsString con marcadores de entorno produce un template literal escapado", () => {
    expect(jsString("plain")).toBe('"plain"');
    expect(jsString(`Bearer ${envMarker("NAHUAL_AUTHORIZATION")}`)).toBe(
      '`Bearer ${env("NAHUAL_AUTHORIZATION")}`',
    );
    expect(jsString(`a\`\${b}\\ ${envMarker("X")}`)).toBe('`a\\`\\${b}\\\\ ${env("X")}`');
    expect(jsString(envMarker("NAHUAL_COOKIE"))).toBe('env("NAHUAL_COOKIE")');
  });
});

describe("fetch() (007, contracts/exporters.md, FR-012)", () => {
  it("GET con headers redactados y lectura JSON según la respuesta", () => {
    expect(render(getItems)).toBe(
      [
        "// Generated by Nahual 1.0.0",
        'const response = await fetch("http://127.0.0.1:4311/export/items?page=1", {',
        '  method: "GET",',
        '  headers: { accept: "application/json", authorization: "<redacted>", "user-agent": "Mozilla/5.0" },',
        "});",
        "const data = await response.json(); // captured: 200 application/json",
        "",
      ].join("\n"),
    );
  });

  it("POST JSON con JSON.stringify del objeto, sin fugas", () => {
    const code = render(postItem);
    expect(code).toContain(
      'body: JSON.stringify({ name: "it\'s \\"x\\" $HOME", password: "<redacted>" }),',
    );
    expect(leaked(code)).toEqual([]);
  });

  it("formulario con URLSearchParams y multipart con FormData sin content-type", () => {
    expect(render(postForm)).toContain(
      'body: new URLSearchParams([["a", "1"], ["session_id", "<redacted>"]]),',
    );
    const upload = render(postUpload);
    expect(upload).toContain(
      'const form = new FormData();\nform.append("note", "hola");\n// omitted file part: file (photo.png)\n',
    );
    expect(upload).toContain("  body: form,");
    expect(upload).not.toContain("multipart/form-data");
  });

  it("body omitido con comentario; respuesta no JSON con text()", () => {
    expect(render(postBig)).toContain("// body omitted: tooLarge (1.5 MB)\n");
    expect(render(postBig)).not.toContain("body:");
  });
});
